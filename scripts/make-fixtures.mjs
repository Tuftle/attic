// writes the small generated exports and their truth files to
// tests/fixtures/<source>/. everything is made up and the same every run.
// a test checks that the committed files match what this writes.

import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

export const ROOT = fileURLToPath(new URL('../tests/fixtures/', import.meta.url));
export const SAMPLE = fileURLToPath(new URL('../site/sample/sample.js', import.meta.url));

/** every fixture file, by path under tests/fixtures */
export async function fixtures() {
  const { spotifyFixture } = await import('../tests/gen/spotify.js');
  const { netflixFixture } = await import('../tests/gen/netflix.js');
  const { youtubeFixture } = await import('../tests/gen/youtube.js');
  const { chatgptFixture, claudeFixture } = await import('../tests/gen/chat.js');
  const { browserFixture } = await import('../tests/gen/browser.js');
  const { letterboxdFixture, goodreadsFixture } = await import('../tests/gen/media.js');
  const { discordFixture } = await import('../tests/gen/discord.js');
  const { stravaFixture } = await import('../tests/gen/strava.js');
  const { appleFixture } = await import('../tests/gen/apple.js');
  const { steamFixture, amazonFixture } = await import('../tests/gen/shop.js');
  const out = {};
  const add = (dir, name, fx) => {
    out[`${dir}/${name}`] = fx.zip;
    out[`${dir}/truth.json`] = JSON.stringify({ zone: fx.zone, now: new Date(fx.now).toISOString(), years: fx.truth }, null, 1) + '\n';
  };
  add('spotify', 'my_spotify_data.zip', spotifyFixture());
  add('netflix', 'netflix-report.zip', netflixFixture());
  add('youtube', 'takeout-youtube.zip', youtubeFixture());
  add('chatgpt', 'chatgpt-export.zip', chatgptFixture());
  add('claude', 'claude-export.zip', claudeFixture());
  add('browser', 'browser-history.zip', await browserFixture());
  add('letterboxd', 'letterboxd-export.zip', letterboxdFixture());
  add('goodreads', 'goodreads-export.zip', goodreadsFixture());
  add('discord', 'package.zip', discordFixture());
  add('strava', 'strava-export.zip', stravaFixture());
  add('apple', 'apple-media-services.zip', appleFixture());
  add('steam', 'steam-licences.zip', steamFixture());
  add('amazon', 'amazon-orders.zip', amazonFixture());
  return out;
}

/**
 * the built-in example year: a smaller made-up 2024 and 2025 from the same
 * generators, as base64 in a module, because the page cannot fetch files.
 */
export async function sample() {
  const sp = await import('../tests/gen/spotify.js');
  const nf = await import('../tests/gen/netflix.js');
  const yt = await import('../tests/gen/youtube.js');
  const ch = await import('../tests/gen/chat.js');
  const md = await import('../tests/gen/media.js');
  const sv = await import('../tests/gen/strava.js');
  const range = { from: [2024, 0, 3], to: [2025, 11, 30] };
  const plays = sp.makePlays({ seed: 'sample-spotify', ...range, scale: 0.55 });
  const views = nf.makeViews({ seed: 'sample-netflix', ...range }).filter(v => v.profile === 'Sam');
  const watches = yt.makeWatches({ seed: 'sample-youtube', ...range });
  const convs = ch.makeConversations({ seed: 'sample-chat', ...range });
  const files = [
    ['my_spotify_data.zip', sp.zipOf(sp.extendedFiles(plays))],
    ['netflix-report.zip', nf.netflixZip(views)],
    ['takeout-youtube.zip', yt.takeoutZip({ 'watch-history.json': yt.watchJson(watches.filter((_, i) => i % 2 === 0)) })],
    ['chatgpt-export.zip', ch.chatgptZip(convs.filter((_, i) => i % 2 === 0))],
    ['letterboxd-export.zip', md.letterboxdZip(md.makeFilms({ seed: 'sample-letterboxd' }).filter(f => f.t < Date.UTC(2026, 0, 1)))],
    ['strava-export.zip', sv.stravaZip(sv.makeActivities({ seed: 'sample-strava' }).filter(a => a.t < Date.UTC(2026, 0, 1)))],
  ];
  return '// the example year: made-up exports from tests/gen, not anyone\'s real data.\n'
    + '// generated by scripts/make-fixtures.mjs. do not edit.\n'
    + `export const SAMPLE = [\n${files.map(([name, bytes]) => `  { name: '${name}', data: '${Buffer.from(bytes).toString('base64')}' },`).join('\n')}\n];\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(SAMPLE), { recursive: true });
  const js = await sample();
  writeFileSync(SAMPLE, js);
  console.log('wrote site/sample/sample.js', js.length, 'bytes');
  for (const [path, data] of Object.entries(await fixtures())) {
    mkdirSync(dirname(ROOT + path), { recursive: true });
    writeFileSync(ROOT + path, data);
    console.log('wrote', 'tests/fixtures/' + path, typeof data === 'string' ? data.length : data.byteLength, 'bytes');
  }
}
