// writes site/vendor/sql-wasm.wasm.js from site/vendor/sql-wasm.wasm.
// the page cannot fetch the wasm file (connect-src 'none'), so it imports
// the same bytes as base64 from a script instead.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const WASM = fileURLToPath(new URL('../site/vendor/sql-wasm.wasm', import.meta.url));
export const OUT = fileURLToPath(new URL('../site/vendor/sql-wasm.wasm.js', import.meta.url));

export function render(bytes) {
  return '// generated by scripts/vendor-wasm.mjs from sql-wasm.wasm. do not edit.\n'
    + `export default '${Buffer.from(bytes).toString('base64')}';\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render(readFileSync(WASM)));
  console.log('wrote', OUT);
}
